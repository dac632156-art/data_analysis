// 把水彩背景图读成 base64，生成 assets.generated.ts（供导出单文件 HTML 内联）。
// 原因：vite `?inline` 对 4MB/10MB 大图不一定内联，会导致导出 HTML 引用外部 png
// （file:// 打开 404）。生成式 base64 保证单文件自包含。
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const etherealDir = path.join(root, 'src/assets/ethereal');

const card = fs.readFileSync(path.join(etherealDir, '背景.png')).toString('base64');
const slice = fs.readFileSync(path.join(etherealDir, 'bg5.png')).toString('base64');

const out = `// AUTO-GENERATED by scripts/gen-export-assets.mjs — do not edit by hand.
// 水彩背景图 base64 内联，保证导出单文件 HTML 自包含（file:// 打开不 404）。
export const BG_CARD = 'data:image/png;base64,${card}';
export const BG_SLICE = 'data:image/png;base64,${slice}';
`;

const target = path.join(root, 'src/utils/exportComponentHTML/assets.generated.ts');
fs.writeFileSync(target, out);
console.log('[gen-export-assets] 已生成', target, '(' + (out.length / 1024 / 1024).toFixed(1) + ' MB)');
